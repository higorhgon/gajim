# Generates the "omarchy" theme from the colors of the current Omarchy
# (https://omarchy.org) theme, and regenerates it whenever Omarchy
# switches themes. CSSConfig reloads the theme file once it changes.

from __future__ import annotations

import logging
import os
import tempfile
import tomllib
from pathlib import Path
from string import Template

from gi.repository import Gio
from gi.repository import GLib

log = logging.getLogger("gajim.gtk.omarchy")

OMARCHY_CURRENT = Path.home() / ".local/state/omarchy/current"
THEME_NAME = "omarchy"

# Colors older themes may not define, and the color used instead
FALLBACKS = {
    "dark_background": "background",
    "darker_background": "dark_background",
    "lighter_background": "selection",
    "dark_foreground": "muted",
    "orange": "yellow",
    "cyan": "blue",
}

CSS_TEMPLATE = Template("""\
/* Generated by Gajim from the current Omarchy theme, do not edit */

:root {
  --accent-color: $accent;
  --accent-bg-color: $accent;
  --accent-fg-color: $background;

  --window-bg-color: $background;
  --window-fg-color: $foreground;
  --view-bg-color: $background;
  --view-fg-color: $foreground;

  --headerbar-bg-color: $dark_background;
  --headerbar-fg-color: $foreground;
  --headerbar-backdrop-color: $dark_background;

  --sidebar-bg-color: $dark_background;
  --sidebar-fg-color: $foreground;
  --sidebar-backdrop-color: $dark_background;
  --secondary-sidebar-bg-color: $darker_background;
  --secondary-sidebar-fg-color: $foreground;

  --card-bg-color: $lighter_background;
  --card-fg-color: $foreground;
  --popover-bg-color: $lighter_background;
  --popover-fg-color: $foreground;
  --dialog-bg-color: $background;
  --dialog-fg-color: $foreground;

  --destructive-color: $red;
  --destructive-bg-color: $red;
  --success-color: $green;
  --success-bg-color: $green;
  --warning-color: $yellow;
  --warning-bg-color: $yellow;
  --error-color: $red;
  --error-bg-color: $red;
}

.gajim-incoming-nickname {
  color: $red;
}
.gajim-outgoing-nickname {
  color: $blue;
}
.gajim-conversation-text {
  color: inherit;
}
.gajim-status-message {
  color: $cyan;
}
.gajim-user-disconnected {
  color: $red;
}
.gajim-user-connected {
  color: $green;
}
.gajim-status-online {
  color: $green;
}
.gajim-status-away {
  color: $orange;
}
.gajim-status-dnd {
  color: $red;
}
.gajim-status-offline {
  color: $dark_foreground;
}
.gajim-status-connecting {
  color: $blue;
}
""")


class OmarchyTheme:
    def __init__(self, theme_dir: Path) -> None:
        self._theme_path = theme_dir / f"{THEME_NAME}.css"
        self._colors_path = OMARCHY_CURRENT / "theme" / "colors.toml"
        self._monitor: Gio.FileMonitor | None = None
        self._render_id: int | None = None

    @staticmethod
    def is_available() -> bool:
        return OMARCHY_CURRENT.is_dir()

    def start(self) -> None:
        self.render()

        # Omarchy replaces the whole current/theme directory on a switch,
        # so watch its parent for that directory to come back
        directory = Gio.File.new_for_path(str(OMARCHY_CURRENT))
        self._monitor = directory.monitor_directory(
            Gio.FileMonitorFlags.WATCH_MOVES, None
        )
        self._monitor.connect("changed", self._on_changed)

    def _on_changed(
        self,
        _monitor: Gio.FileMonitor,
        file: Gio.File,
        other_file: Gio.File | None,
        _event_type: Gio.FileMonitorEvent,
    ) -> None:
        names = {file.get_basename()}
        if other_file is not None:
            names.add(other_file.get_basename())
        if "theme" not in names:
            return

        if self._render_id is not None:
            GLib.source_remove(self._render_id)
        self._render_id = GLib.timeout_add(50, self._on_render)

    def _on_render(self) -> bool:
        self._render_id = None
        self.render()
        return GLib.SOURCE_REMOVE

    def render(self) -> None:
        try:
            with self._colors_path.open("rb") as file:
                colors = tomllib.load(file)
        except (OSError, tomllib.TOMLDecodeError) as error:
            log.warning("Could not read %s: %s", self._colors_path, error)
            return

        for name, fallback in FALLBACKS.items():
            if name not in colors and fallback in colors:
                colors[name] = colors[fallback]

        try:
            css = CSS_TEMPLATE.substitute(colors)
        except KeyError as error:
            log.warning("Omarchy theme has no color %s", error)
            return

        try:
            unchanged = self._theme_path.read_text(encoding="utf-8") == css
        except OSError:
            unchanged = False
        if unchanged and not self._theme_path.is_symlink():
            return

        # Replace the file atomically, so it is never read half written
        fd, tmp_path = tempfile.mkstemp(
            dir=self._theme_path.parent, prefix=f".{THEME_NAME}-"
        )
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            file.write(css)
        os.replace(tmp_path, self._theme_path)
        log.info("Generated theme from %s", self._colors_path)
