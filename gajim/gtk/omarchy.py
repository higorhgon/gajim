class OmarchyTheme:
    def __init__(self, theme_dir: Path) -> None:
        self._theme_path = theme_dir / f"{THEME_NAME}.css"
        self._colors_path = OMARCHY_CURRENT / "theme" / "colors.toml"
        self._monitor: Gio.FileMonitor | None = None
        self._render_id: int | None = None

    @staticmethod
    def is_available() -> bool:
        return OMARCHY_CURRENT.is_dir()

    def exists(self) -> bool:
        return self._theme_path.exists()

    def start(self) -> None:
        self.render()

        # Omarchy replaces the whole current/theme directory on a switch,
        # so watch its parent for that directory to come back
        directory = Gio.File.new_for_path(str(OMARCHY_CURRENT))
        self._monitor = directory.monitor_directory(
            Gio.FileMonitorFlags.WATCH_MOVES, None
        )
        self._monitor.connect("changed", self._on_changed)

    def _on_changed(
        self,
        _monitor: Gio.FileMonitor,
        file: Gio.File,
        other_file: Gio.File | None,
        _event_type: Gio.FileMonitorEvent,
    ) -> None:
        names = {file.get_basename()}
        if other_file is not None:
            names.add(other_file.get_basename())
        if "theme" not in names:
            return

        if self._render_id is not None:
            GLib.source_remove(self._render_id)
        self._render_id = GLib.timeout_add(50, self._on_render)

    def _on_render(self) -> bool:
        self._render_id = None
        self.render()
        return GLib.SOURCE_REMOVE

    def render(self) -> None:
        try:
            with self._colors_path.open("rb") as file:
                colors = tomllib.load(file)
        except (OSError, tomllib.TOMLDecodeError) as error:
            log.warning("Could not read %s: %s", self._colors_path, error)
            return

        for name, fallback in FALLBACKS.items():
            if name not in colors and fallback in colors:
                colors[name] = colors[fallback]

        try:
            css = CSS_TEMPLATE.substitute(colors)
        except KeyError as error:
            log.warning("Omarchy theme has no color %s", error)
            return

        try:
            unchanged = self._theme_path.read_text(encoding="utf-8") == css
        except OSError:
            unchanged = False
        if unchanged and not self._theme_path.is_symlink():
            return

        # Replace the file atomically, so it is never read half written
        fd, tmp_path = tempfile.mkstemp(
            dir=self._theme_path.parent, prefix=f".{THEME_NAME}-"
        )
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            file.write(css)
        os.replace(tmp_path, self._theme_path)
        log.info("Generated theme from %s", self._colors_path)


def install_bar_plugin(source_dir: Path, marker: Path) -> None:
    """Install the bar widget which stands in for the tray icon, and keep
    it up to date. The first install also puts it in the bar and hides the
    tray icon; once the user removes the plugin it stays removed."""

    plugin_dir = OMARCHY_CONFIG / "plugins" / BAR_PLUGIN_ID
    if plugin_dir.is_dir():
        comparison = filecmp.dircmp(source_dir, plugin_dir)
        if comparison.left_only or comparison.diff_files:
            shutil.copytree(source_dir, plugin_dir, dirs_exist_ok=True)
            log.info("Updated the Omarchy bar plugin")
        return

    if marker.exists():
        return

    try:
        shutil.copytree(source_dir, plugin_dir)
        marker.touch()
    except OSError as error:
        log.warning("Could not install the Omarchy bar plugin: %s", error)
        return

    log.info("Installed the Omarchy bar plugin")
    command = "omarchy-shell shell rescanPlugins"
    if not _enable_bar_plugin():
        # Without a shell.json of its own the shell uses its defaults, which
        # the CLI knows how to extend
        command += f"; omarchy plugin enable {BAR_PLUGIN_ID} --section tray"
    _spawn(["sh", "-c", command])


def _enable_bar_plugin() -> bool:
    """Adds the widget to the tray's section and hides the tray icon, in one
    write to shell.json, which the shell watches"""

    config_path = OMARCHY_CONFIG / "shell.json"
    try:
        config = json.loads(config_path.read_text(encoding="utf-8"))
        layout = config["bar"]["layout"]
    except (OSError, ValueError, KeyError, TypeError):
        return False

    widget = {"id": BAR_PLUGIN_ID}
    placed = any(
        isinstance(entry, dict) and entry.get("id") == BAR_PLUGIN_ID
        for entries in layout.values()
        if isinstance(entries, list)
        for entry in entries
    )
    for entries in layout.values():
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if not isinstance(entry, dict) or entry.get("id") != "omarchy.tray":
                continue
            hidden = entry.setdefault("hidden", [])
            if TRAY_ITEM_ID not in hidden:
                hidden.append(TRAY_ITEM_ID)
            if TRAY_ITEM_ID in entry.get("pinned", []):
                entry["pinned"].remove(TRAY_ITEM_ID)
            break

    if not placed:
        layout.setdefault("tray", []).append(widget)

    fd, tmp_path = tempfile.mkstemp(dir=config_path.parent, prefix=".shell-")
    with os.fdopen(fd, "w", encoding="utf-8") as file:
        json.dump(config, file, indent=2, ensure_ascii=False)
        file.write("\n")
    os.replace(tmp_path, config_path)
    return True


def _spawn(argv: list[str]) -> None:
    try:
        Gio.Subprocess.new(argv, Gio.SubprocessFlags.NONE)
    except GLib.Error as error:
        log.warning("Could not run %s: %s", argv, error)
